"""Deterministic owned finite amphibious content; no original assets or runtime required."""
from pathlib import Path
import json, shutil, struct, zlib

ROOT=Path(__file__).resolve().parents[2]
DEST=ROOT/'SimulationTest/public/inputs/amphibious-production'

def png(width,height,kind):
    # New geometric artwork, drawn from integer coordinates rather than an input bitmap.
    polygons = {
        'body': [(13,0),(18,5),(25,9),(22,13),(16,12),(13,15),(10,12),(3,13),(0,9),(8,5)],
        'wing': [(7,0),(13,8),(11,26),(7,30),(3,26),(0,8)],
        'factory': [(2,4),(10,4),(10,0),(30,0),(30,4),(38,4),(38,61),(2,61)],
    }
    shape='wing' if kind.startswith('wing') else 'factory' if kind=='factory' else 'body'
    basis={'wing':(14,30),'factory':(40,63),'body':(26,15)}[shape]
    poly=[(x*width/basis[0],y*height/basis[1]) for x,y in polygons[shape]]
    def inside(x,y):
        hit=False
        for i,(a,b) in enumerate(poly):
            c,d=poly[i-1]
            if (b>y)!=(d>y) and x<(c-a)*(y-b)/(d-b)+a:hit=not hit
        return hit
    color=(40,48,55,110) if kind=='shadow' else (80,65,56,255) if kind=='dead' else (63,133,146,255)
    rows=[]
    for y in range(height):
        row=bytearray([0])
        for x in range(width):
            rgba=color if inside(x+.5,y+.5) else (0,0,0,0)
            if rgba[3] and kind not in {'dead','shadow'} and x in range(width//2-1,width//2+1):rgba=(183,221,224,255)
            row.extend(rgba)
        rows.append(row)
    def chunk(k,b):return struct.pack('>I',len(b))+k+b+struct.pack('>I',zlib.crc32(k+b)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,height,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b'')

def write_native(path,values):
    text='\n'.join(f'{k}={v}' for k,v in values.items())+'\n' if path.suffix=='.ini' else json.dumps(values,indent=2)+'\n'
    path.write_text(text,encoding='utf8')

def generate():
    assert not DEST.exists(), 'Never overwrite an existing fixture batch'
    for fmt in ['ini','json','hjson']:
        source=ROOT/f'SimulationTest/public/inputs/helicopter-production/{fmt}/production-package'
        pack=DEST/fmt/'production-package'
        shutil.copytree(source,pack)
        units=pack/'units'
        t1=dict(format='rw-reforge.native-air-factory.v2',name='airFactory',techLevel=1,maxHp=1000,radius=30,
            footprint='-1,-1,1,1',placementFootprint='-1,-1,1,2',movementType='NONE',productionUnits='helicopter',
            price=1000,buildSpeed=.001,fogOfWarSightRange=15,image='air_factory.png',image_dead='air_factory_dead.png',
            upgradeTo='airFactoryT2',upgradePrice=1500,upgradeBuildSpeed=.0004)
        t2={k:v for k,v in t1.items() if k not in ['upgradeTo','upgradePrice','upgradeBuildSpeed']}
        t2.update(name='airFactoryT2',techLevel=2,price=2500,productionUnits='helicopter,amphibiousJet',image='air_factory_t2.png')
        write_native(units/f'airFactory.{fmt}',t1);write_native(units/f'airFactoryT2.{fmt}',t2)
        (units/'air_factory_t2.png').write_bytes(png(40,63,'factory'))
        jet=dict(format='rw-reforge.native-amphibious-jet.v1',name='amphibiousJet',maxHp=530,radius=12,
            price=2000,buildSpeed=.001,image='jet.png',image_dead='jet_dead.png',image_shadow='jet_shadow.png',
            image_wing_left='jet_left.png',image_wing_right='jet_right.png')
        write_native(units/f'amphibiousJet.{fmt}',jet)
        for name,kind,w,h in [('jet.png','body',15,26),('jet_dead.png','dead',15,26),('jet_shadow.png','shadow',15,26),
                              ('jet_left.png','wing-left',30,14),('jet_right.png','wing-right',30,14)]:
            (units/name).write_bytes(png(w,h,kind))
        manifest=json.loads((pack/'pack.json').read_text(encoding='utf8'))
        manifest.update(id=f'p009-amphibious-production-{fmt}',name='Owned native amphibious production chain')
        manifest['units'] += [dict(type='air-factory',file=f'units/airFactoryT2.{fmt}'),
                              dict(type='amphibious-jet',file=f'units/amphibiousJet.{fmt}')]
        (pack/'pack.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8')
    add_scene_inputs()
    (DEST/'README.md').write_text('# Owned amphibious production fixtures\n\n'
        'Generated by SimulationTest/tools/amphibious_fixture.py. Builder, helicopter and factory assets reuse existing owned helicopter-production fixtures. '
        'The five jet sprites are newly drawn integer-coordinate geometric art. No original game images, audio, bytecode or derived pixels are included. '
        'Native behavior values are independently implemented from private qualified evidence; the original core is not a runtime dependency.\n',encoding='utf8')

def add_scene_inputs():
    """Complete the normal opening using existing owned finite fixtures, without overwriting."""
    for fmt in ['ini','json','hjson']:
        root=DEST/fmt
        pack=root/'production-package'
        assert not (root/'maps').exists(), 'Scene inputs already exist'
        command=ROOT/f'SimulationTest/public/inputs/hover-production/{fmt}/package/units/commandCenter'
        command_dest=pack/'units/commandCenter'
        command_dest.mkdir()
        for name in [f'commandCenter.{fmt}','base.png','base_back.png','base_dead.png']:
            shutil.copy2(command/name,command_dest/name)
        naval=ROOT/f'SimulationTest/public/inputs/naval-production/{fmt}'
        for directory,names in [('land',[f'tank.{fmt}','tank.png','tank_dead.png','tank_turret.png']),
                                ('naval',[f'underwaterTarget.{fmt}','underwater_target.png'])]:
            dest=pack/'units'/directory
            dest.mkdir()
            for name in names:shutil.copy2(naval/'production-package/units'/directory/name,dest/name)
        (root/'maps').mkdir();(root/'assets').mkdir()
        shutil.copy2(naval/'maps/naval-shore.tmx',root/'maps/naval-shore.tmx')
        shutil.copy2(naval/'assets/naval-ground.png',root/'assets/naval-ground.png')
        manifest=json.loads((pack/'pack.json').read_text(encoding='utf8'))
        manifest['units'] += [dict(type='command-center',file=f'units/commandCenter/commandCenter.{fmt}'),
            dict(type='tank',file=f'units/land/tank.{fmt}'),dict(type='underwater-target',file=f'units/naval/underwaterTarget.{fmt}')]
        (pack/'pack.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8')

if __name__=='__main__':generate()
