"""Owned AA fixtures and contracts fixed before public simulator execution."""
from pathlib import Path
import hashlib
import json

PUBLIC = Path(__file__).resolve().parents[1] / 'public'


def write(path, value):
    assert not path.exists(), f'Never overwrite an existing batch: {path}'
    path.write_text(json.dumps(value, indent=2) + '\n', encoding='utf8')


def generate():
    for fmt in ('ini', 'json', 'hjson'):
        root = PUBLIC / f'inputs/aa-beam-production/{fmt}'
        prefix = f'../inputs/aa-beam-production/{fmt}/'
        files = {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in sorted(root.rglob('*')) if p.is_file()}
        pack = json.loads((root / 'production-package/pack.json').read_text(encoding='utf8'))
        refs = []
        for entry in pack['units']:
            name = 'production-package/' + entry['file']
            unit_id = {'tank': 'c_tank', 'underwater-target': 'navalUnderwaterTarget'}.get(entry['type'], Path(entry['file']).stem)
            loader = {'air-factory': 'factory', 'tank': 'declared-tank'}.get(entry['type'], entry['type'])
            refs.append(dict(id=unit_id, path=prefix+name, sha256=files[name], loader=loader))
        used = {r['path'].removeprefix(prefix) for r in refs} | {'maps/naval-shore.tmx'}
        scene = json.loads((PUBLIC / f'scenarios/air-transport-{fmt}-short.json').read_text(encoding='utf8'))
        for key in ('intents', 'contentPack'):
            scene.pop(key, None)
        scene.update(scenarioId='p009-aa-beam-combat', inputs=prefix.removesuffix('/'))
        scene['content'] = dict(map=dict(id='map', path=prefix+'maps/naval-shore.tmx', sha256=files['maps/naval-shore.tmx']),
            unitVariants=refs, dependencies=[dict(id=f'dep-{i}', path=prefix+name, sha256=sha)
                for i, (name, sha) in enumerate(files.items()) if name not in used])
        scene['units'] = [dict(unitId=name, owner=owner, type='aaBeamGunship', position=dict(x=x,y=150), heading=heading)
                          for name,owner,x,heading in [('aa','p1',150,90),('enemy','p2',350,270)]]
        scene['actions'] = []
        scene['combatContract'] = dict(worldSeed=12345, initialFrameCounter=-1, unitObjectIds=dict(aa=8,enemy=9),nextObjectId=10)
        scene['termination']['steps'] = [dict(stepIndex=t,delta=1,deltaUnit='sim-tick') for t in range(260)]
        scene['automaticVision'] = dict(retention='MEMORY',pathSource='PLAYER_KNOWLEDGE',
            shareAlliedVision=False,observers=['p1'],grid=dict(width=40,height=30))
        scene['testScene'] = dict(formatVersion=1,displayName=f'AA beam combat ({fmt})',
            summary='Owned air-only paid instant beam, visible reuse and full energy recharge; production is separate.',files=files)
        # These literal expectations come from the 6/.5/.01/.05 qualified contract,
        # not from traces generated by the implementation.
        def equal(path,value): return dict(path=path,operator='equals',value=value)
        contract = dict(schemaVersion=1,kind='behavior-contract',contractId=f'public.aa-beam-{fmt}.short.contract.v1',
            scope='self-behavior',scenarioIds=['p009-aa-beam-combat'],
            comparison=dict(numberMode='declared-per-field',tolerances={}),
            approval=dict(status='tool-fixture-only',source='ENG-P009-009 qualified DEC static facts; owned self-behavior only'),
            exclusions=['original-compatibility','platform-input','performance'],rules=[
                dict(ruleId='initial-energy',when=dict(phase='initial',stepIndex=0),assertions=[
                    equal('units.aa.energy.current',6),equal('units.aa.energy.recharging',False),equal('units.enemy.health',2500)]),
                dict(ruleId='thirteen-paid-shots-and-full-recharge-lock',when={'phase':'after-advance','stepIndex':100},assertions=[
                    equal('units.aa.energy.recharging',True),equal('units.enemy.health',2214)])])
        write(PUBLIC/f'scenarios/aa-beam-{fmt}-short.json',scene)
        write(PUBLIC/f'contracts/aa-beam-{fmt}-short.json',contract)


def generate_platform():
    for fmt in ('ini', 'json', 'hjson'):
        plan = json.loads((PUBLIC/f'platform/scenarios/air-transport-{fmt}-production-chain.json').read_text(encoding='utf8'))
        plan.update(scenarioId=f'aa-beam-{fmt}-production-chain',inputs=f'../../inputs/aa-beam-production/{fmt}')
        plan.pop('windowsPausedIntents',None)
        intents=plan['intents'][:13]
        def intent(name,kind,wait=0,point=None,**values):
            return dict(intentId=name,kind=kind,waitSteps=wait,
                **(dict(position=dict(x=point[0],y=point[1])) if point else {}),**values)
        intents += [intent('produce-air','produce',600,typeId='aaBeamGunship'),
            *[intent(f'wait-air-{i}','select',600,(270,150)) for i in range(1,4)],
            intent('select-air','select',point=(269,203)),
            intent('approach-air','move',400,(440,300)),intent('stop-air','stop',40),
            intent('attack-air','attack',260,(580,265)),intent('return-home','move',400,(300,250)),
            intent('stop-home','stop',40)]
        # The click hits the elevated sprite; the independent archive check
        # binds its fixed enemy identity and exact ground position separately.
        attack = next(i for i in intents if i['intentId'] == 'attack-air')
        attack.update(targetUnitId='b', targetGroundPosition=dict(x=580,y=300))
        plan['intents']=intents
        plan['waitPlan']={i['intentId']:dict(minimumSteps=i['waitSteps'],timeoutSeconds=240)
                          for i in intents if i['waitSteps']}
        contract=json.loads((PUBLIC/f'platform/contracts/air-transport-{fmt}-production-chain.json').read_text(encoding='utf8'))
        contract['scenarioId']=plan['scenarioId']
        contract['rules']=[dict(intentId=i['intentId']) for i in intents]
        history=contract['history']
        history.pop('transportStages')
        history['productionOrder']=['builder','aaBeamGunship']
        history['projectileBirthsRequired']=True
        history['spend'][-1]['amount']=6000
        history['finalUnits']=[dict(ownerPlayerId='p1',typeId=k,fields=dict(alive=True))
            for k in ('commandCenter','builder','airFactoryT2','aaBeamGunship')]
        write(PUBLIC/f'platform/scenarios/aa-beam-{fmt}-production-chain.json',plan)
        write(PUBLIC/f'platform/contracts/aa-beam-{fmt}-production-chain.json',contract)


if __name__ == '__main__':
    generate()
    generate_platform()
